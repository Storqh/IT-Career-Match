# =========================================================
# 3. CONVERT SQLITE TIMESTAMP
# =========================================================

def convert_value(value, column_type):
    if value is None:
        return None

    if column_type.upper() == "TIMESTAMP":
        if isinstance(value, datetime):
            return value

        return datetime.fromisoformat(
            str(value).replace("Z", "+00:00")
        )

    return value


# =========================================================
# 4. MAIN MIGRATION
# =========================================================

def migrate():
    if not SQLITE_PATH.exists():
        raise FileNotFoundError(
            f"Không tìm thấy SQLite database: {SQLITE_PATH}"
        )

    sqlite_conn = sqlite3.connect(SQLITE_PATH)

    try:
        with psycopg.connect(DATABASE_URL) as pg_conn:

            with pg_conn.transaction():

                # -----------------------------------------
                # CREATE POSTGRESQL TABLES
                # -----------------------------------------

                for statement in SCHEMA:
                    pg_conn.execute(statement)

                print("Đã kiểm tra/tạo schema PostgreSQL.")

                # -----------------------------------------
                # SAFETY CHECK: TARGET MUST BE EMPTY
                # -----------------------------------------

                for table in TABLES:
                    count = pg_conn.execute(
                        sql.SQL("SELECT COUNT(*) FROM {}").format(
                            sql.Identifier(table)
                        )
                    ).fetchone()[0]

                    if count > 0:
                        raise RuntimeError(
                            f"Bảng PostgreSQL '{table}' "
                            f"đã có {count} bản ghi. "
                            "Dừng để tránh ghi đè dữ liệu."
                        )

                print("Các bảng PostgreSQL đang trống.")

                # -----------------------------------------
                # MIGRATE TABLES
                # -----------------------------------------

                source_counts = {}

                for table in TABLES:
                    print(f"\nĐang chuyển bảng: {table}")

                    source_cursor = sqlite_conn.execute(
                        f'SELECT * FROM "{table}"'
                    )

                    column_info = sqlite_conn.execute(
                        f'PRAGMA table_info("{table}")'
                    ).fetchall()

                    columns = [
                        item[1] for item in column_info
                    ]

                    column_types = {
                        item[1]: item[2]
                        for item in column_info
                    }

                    rows = source_cursor.fetchall()

                    source_counts[table] = len(rows)

                    if not rows:
                        print("  Không có dữ liệu.")
                        continue

                    placeholders = sql.SQL(", ").join(
                        sql.Placeholder() for _ in columns
                    )

                    insert_query = sql.SQL(
                        "INSERT INTO {} ({}) VALUES ({})"
                    ).format(
                        sql.Identifier(table),
                        sql.SQL(", ").join(
                            sql.Identifier(column)
                            for column in columns
                        ),
                        placeholders
                    )

                    converted_rows = []

                    for row in rows:
                        converted_row = tuple(
                            convert_value(
                                value,
                                column_types[column]
                            )
                            for column, value in zip(columns, row)
                        )

                        converted_rows.append(converted_row)

                    pg_conn.cursor().executemany(
                        insert_query,
                        converted_rows
                    )

                    print(
                        f"  Đã chuyển {len(rows)} bản ghi."
                    )

                # -----------------------------------------
                # RESET IDENTITY SEQUENCES
                # -----------------------------------------

                for table, primary_key in PRIMARY_KEYS.items():

                    max_id = pg_conn.execute(
                        sql.SQL(
                            "SELECT MAX({}) FROM {}"
                        ).format(
                            sql.Identifier(primary_key),
                            sql.Identifier(table)
                        )
                    ).fetchone()[0]

                    pg_conn.execute(
                        """
                        SELECT setval(
                            pg_get_serial_sequence(%s, %s),
                            %s,
                            %s
                        )
                        """,
                        (
                            table,
                            primary_key,
                            max_id if max_id is not None else 1,
                            max_id is not None
                        )
                    )

                print("\nĐã đồng bộ IDENTITY.")

                # -----------------------------------------
                # VERIFY RECORD COUNTS
                # -----------------------------------------

                print("\n========== VERIFY ==========")

                for table in TABLES:
                    target_count = pg_conn.execute(
                        sql.SQL("SELECT COUNT(*) FROM {}").format(
                            sql.Identifier(table)
                        )
                    ).fetchone()[0]

                    source_count = source_counts[table]

                    print(
                        f"{table:<20} "
                        f"SQLite: {source_count:<5} "
                        f"PostgreSQL: {target_count}"
                    )

                    if source_count != target_count:
                        raise RuntimeError(
                            f"Số bản ghi không khớp ở bảng {table}"
                        )

                print("\nMIGRATION SUCCESSFUL!")

    finally:
        sqlite_conn.close()


if __name__ == "__main__":
    migrate()
